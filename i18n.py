# "sub-" and "sub-sub-" prefixes per language
_SUB = {
    "hi": ("उप-", "उप-उप-"), "bn": ("উপ-", "উপ-উপ-"), "as": ("উপ-", "উপ-উপ-"),
    "gu": ("પેટા ", "પેટા-પેટા "), "kn": ("ಉಪ ", "ಉಪ-ಉಪ "), "ml": ("ഉപ ", "ഉപ-ഉപ "),
    "mr": ("उप-", "उप-उप-"), "or": ("ଉପ-", "ଉପ-ଉପ-"), "pa": ("ਉਪ-", "ਉਪ-ਉਪ-"),
    "ta": ("துணை ", "துணை-துணை "), "te": ("ఉప ", "ఉప-ఉప "),
}

TRANSLATIONS: dict[str, dict[str, str]] = {lang: {} for lang in LANGS}


def _build() -> None:
    parsed = {k: dict(zip(_ORDER, v.split("|"))) for k, v in _BASE.items()}
    for k, tr in parsed.items():
        assert len(tr) == len(_ORDER), k
    for lang in LANGS:
        t = TRANSLATIONS[lang]
        for base in _BASE:
            if base == "caption":
                continue
            t[base] = base.replace("-", " ") if lang == "en" else parsed[base][lang]
        for derived, (a, b) in {"figure-caption": ("figure", "caption"), "table-caption": ("table", "caption")}.items():
            t[derived] = f"{t[a]} {t[b] if b in t else ('caption' if lang == 'en' else parsed['caption'][lang])}"
        for level, idx in (("sub", 0), ("subsub", 1)):
            for core in ("headline", "section-title", "ordered-list", "unordered-list"):
                name = f"{level}-{core}"
                if lang == "en":
                    t[name] = ("sub-" if level == "sub" else "sub-sub-") + core.replace("-", " ")
                else:
                    t[name] = _SUB[lang][idx] + t[core]


_build()


def label(lang: str, cls_name: str) -> str:
    """Localised label for an IndicDLP class name (falls back to the English name)."""
    return TRANSLATIONS.get(lang, {}).get(cls_name, cls_name)
